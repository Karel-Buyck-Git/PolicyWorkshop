"""The engine writes LF on every host (#52).

This is the regression guard for the defect that made ``examples/contoso/verify.sh``
unpassable on any Windows checkout: the renderers wrote through ``Path.write_text``
with no ``newline=``, so the generated bytes carried the host's native line ending
while ``.gitattributes`` (``eol=lf``) checked the fixtures out as LF. The byte-diff
then compared CRLF against LF and failed for a non-reason — and it failed
*intermittently*, because a fixture last written by the renderer was CRLF while one
last written by git was LF.

CI runs on ubuntu, where both sides are LF and the bug is invisible. So this test is
the only thing standing between the repo and a silent repeat.
"""
import tempfile
import unittest
from pathlib import Path

import _engine_path  # noqa: F401

from epac_builder.writeutil import write_json, write_text  # noqa: E402


class TestWritersEmitLF(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_write_text_emits_no_carriage_returns(self):
        path = self.tmp / "a.txt"
        write_text(path, "first\nsecond\nthird\n")
        self.assertEqual(path.read_bytes(), b"first\nsecond\nthird\n")

    def test_write_json_emits_no_carriage_returns(self):
        path = self.tmp / "a.json"
        write_json(path, {"one": 1, "nested": {"two": [1, 2]}})
        self.assertNotIn(b"\r", path.read_bytes())

    def test_write_text_appends_the_trailing_newline(self):
        path = self.tmp / "b.txt"
        write_text(path, "no trailing newline")
        self.assertEqual(path.read_bytes(), b"no trailing newline\n")

    def test_write_json_is_stable_and_preserves_insertion_order(self):
        path = self.tmp / "b.json"
        # Keys are deliberately NOT sorted by the writer — callers build dicts in a
        # deterministic order so EPAC files stay human-readable.
        write_json(path, {"zebra": 1, "alpha": 2})
        self.assertEqual(path.read_text(encoding="utf-8"),
                         '{\n  "zebra": 1,\n  "alpha": 2\n}\n')

    def test_writers_create_missing_parent_directories(self):
        path = self.tmp / "deep" / "deeper" / "c.json"
        write_json(path, {"ok": True})
        self.assertTrue(path.exists())

    def test_non_ascii_survives_as_utf8_not_escapes(self):
        path = self.tmp / "d.json"
        write_json(path, {"display": "Management Essential — Tags"})
        self.assertIn("—", path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
