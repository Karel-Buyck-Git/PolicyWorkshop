"""Generate custom DLW mandatory-tags Azure Policy definitions (`dlw-az-tagging`).

Policy-side mirror of `getResourceTags.bicep`: validates that resources carry the
organisation's **mandatory tags** (presence only — values are owned by the deploying
Bicep). Declares a **NewGroup** overlay; the scaffold derives the names/paths/artifacts
from `shared/naming.py`. The policy *rule* (the mandatory-tag list) is this gen's own.

Run standalone for a preview, or via the producer's `apply_overlays.py` step:

    python engine/definition_gen/gen_dlw_tagging_definitions.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # engine/ root
from definition_gen import scaffold  # noqa: E402
from definition_gen.scaffold import Overlay, NewGroup  # noqa: E402

SOURCE = "getResourceTags.bicep"
FAMILY = "dlw-az-tagging"

# The convention the policy enforces (edit here, then re-run).
MANDATORY_TAGS = ["environment", "costCenter", "workload", "owner", "creationDate", "service"]
OPTIONAL_TAGS = ["description"]            # present-but-not-validated; deployers may add more
DEF_NAME = "tagging-require-mandatory-tags"

RATIONALE = (
    "**Essential** — Mandatory-tag guardrails for every taggable Azure resource: audits "
    "(or denies) resources missing the organisation's mandatory tags. Consistent tags are "
    "baseline hygiene — they underpin cost allocation, ownership, automation and incident "
    "response. Effects default to Audit and are tuned from a single initiative parameter."
)

USAGE_MD = [
    "## Product, purpose & deployment", "",
    "**Product.** Part of DLW's Azure tagging governance as code — generated by "
    "`engine/definition_gen/gen_dlw_tagging_definitions.py` from the dlw MSPE `getResourceTags.bicep` "
    "convention.", "",
    "**Purpose.** Where `getResourceTags.bicep` *applies* mandatory tags at deploy time, these "
    "policies *verify* their presence at the platform — catching resources created outside the module.", "",
    "> ⚠️ **Ships as `Audit`.** Set the initiative's top-level `effect` parameter to `Deny` at "
    "assignment time to enforce. The policy validates tag **presence** only — values are owned by "
    "the deploying Bicep.", "",
    f"**Mandatory tags:** {', '.join(MANDATORY_TAGS)}.  **Optional (not validated):** "
    f"{', '.join(OPTIONAL_TAGS)}.", "",
]


def _definition():
    """The mandatory-tag presence policy; the `anyOf` is generated from MANDATORY_TAGS."""
    missing = []
    for tag in MANDATORY_TAGS:
        missing.append({"field": f"tags['{tag}']", "exists": "false"})
        missing.append({"field": f"tags['{tag}']", "equals": ""})
    desc = scaffold.cap(
        f"Audits or denies resources missing (or with an empty value for) any mandatory tag "
        f"({', '.join(MANDATORY_TAGS)}). Validates tag PRESENCE only — the values are supplied by "
        f"the deploying Bicep; {', '.join(OPTIONAL_TAGS)} is optional and not validated, and extra "
        f"tags are allowed. Land as 'Audit' for brownfield discovery, then 'Deny' to enforce on new "
        f"deployments (Deny gates create/update only — it never touches existing resources).")
    return {
        "name": DEF_NAME,
        "properties": {
            "displayName": "Require mandatory tags on resources",
            "description": desc,
            "policyType": "Custom",
            "mode": "Indexed",
            "metadata": {
                "category": "Tags", "version": "1.0.0", "source": SOURCE,
                "cafCategory": "Governance", "checkKind": "presence",
                "mandatoryTags": MANDATORY_TAGS, "optionalTags": OPTIONAL_TAGS,
            },
            "parameters": {
                "excludedResourceTypes": {
                    "type": "Array", "defaultValue": [],
                    "metadata": {"displayName": "Excluded resource types",
                                 "description": "Resource types matching any of these wildcard patterns are "
                                                "exempt from the tag check. Useful for child/proxy resource "
                                                "types that do not support tags. Example: 'Microsoft.Network/*/*, "
                                                "Microsoft.Insights/diagnosticSettings'."},
                },
                "effect": {
                    "type": "String", "allowedValues": ["Audit", "Deny", "Disabled"], "defaultValue": "Audit",
                    "metadata": {"displayName": "Effect",
                                 "description": "The effect of the policy (Audit, Deny or Disabled)."},
                },
            },
            "policyRule": {
                "if": {"allOf": [
                    {"count": {"value": "[parameters('excludedResourceTypes')]", "name": "excludedType",
                               "where": {"field": "type", "like": "[current('excludedType')]"}}, "equals": 0},
                    {"anyOf": missing},
                ]},
                "then": {"effect": "[parameters('effect')]"},
            },
        },
    }


def build():
    return Overlay(
        family=FAMILY,
        placement=NewGroup("Management", "Essential", "Tagging", "tagging", RATIONALE),
        definitions=[_definition()],
        source=SOURCE,
        usage_md=USAGE_MD,
    )


def main():
    result = scaffold.apply(build())
    print(f"[{FAMILY}] 1 definition -> {result['kind']} group '{result['name']}'")


if __name__ == "__main__":
    main()
